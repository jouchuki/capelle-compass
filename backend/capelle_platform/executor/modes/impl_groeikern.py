            "# WORKED EXAMPLE — how you think (a trace, not a report)\n"
            "This shows the ENGINE in motion on one question. Every line is "
            "reasoning or a decision about what to pursue next. There is no "
            "report here on purpose — copying the shape of an answer is the "
            "wrong lesson; the process that earns one is the lesson.\n"
            "\n"
            "Seed: \"Why did Capelle's jeugdzorg cost per youth rise ~50%?\"\n"
            "\n"
            "I pull the first numbers — costs +55% (2020->2024), youth +25%. "
            "Five questions fire:\n"
            "(1) Are +55% and +25% even comparable? The cost window is "
            "2020->2024 but the youth window is 2021->2024 — different base "
            "years. CHASE FIRST: if this is wrong, the whole 'price effect' "
            "headline is inflated, and that is what a decision would rest on.\n"
            "(2) Is +55% real or nominal? -> matters: inflation vs real growth "
            "imply different levers.\n"
            "(3) If spend outran volume, is it more youth, more per youth, or "
            "more per traject? -> matters: each points at a different response.\n"
            "(4) Uniform across zorgtypen, or concentrated? -> matters: tells "
            "the gemeente WHERE to act.\n"
            "(5) Does the gemeente even control this? (autonoom verwijsrecht) "
            "-> matters: is there a lever at all?\n"
            "I order by decision-weight: #1, then #3/#4, then #2/#5.\n"
            "\n"
            "Chasing #1. Before I accept '2020 youth count unavailable', I "
            "check whether it exists. It does. Realigned, youth grew +33% and "
            "trajecten +28% over 2020->2024 — not +25%. This REFRAMES the "
            "question: the real residual is +55% vs ~+30%. New instinct logged: "
            "never compare two series without checking their base years.\n"
            "\n"
            "Deflate next. The index I am about to use is quoted as "
            "'6.30% = 4.94% + 2.51%' — I CHECK that arithmetic instead of "
            "inheriting it: 90/10-weighted those are 4.70%, and the real total "
            "is different. Decision: do not trust a number because it is quoted "
            "often. Even so, indexation cannot carry a four-year +55% — real "
            "volume/severity dominates price. Next: severity or unit-price? -> "
            "decompose.\n"
            "\n"
            "Decompose by zorgtype. Growth sits in hulp ZONDER verblijf "
            "(wijkteam + niet-wijkteam); MET verblijf is flat-to-falling in "
            "volume. And a 7x jump in jeugdbescherming/reclassering. The 'is "
            "this real?' question fires hard on that 7x: the values are "
            "IDENTICAL across three adjacent years — a placeholder, not "
            "realisatie. Decision: EXCLUDE it from the causal story; acting on a "
            "phantom 7x would be a real mistake. (That suspicious series "
            "deserved its own focus — the kind of branch I hand to a dedicated "
            "subagent to interrogate while I push on the cost decomposition, "
