            "# TERM INTERPRETATION\n"
            "When the user asks for a slice CBS does not publish (e.g. "
            "'alleenstaande moeders' — there is no wijk-level gender split), "
            "fall back to the closest non-gendered CBS variable and STATE the "
            "proxy explicitly in the narrative. See `/cbs` for the specific "
