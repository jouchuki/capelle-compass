            "MECHANISM (unchanged, non-negotiable): the ONLY way to ask is the "
            "`capelle-ask` shell command via Bash. NEVER call the built-in "
            "`AskUserQuestion` tool — in this environment it is a no-op that "
            "silently discards the question. When you do ask, `capelle-ask` MUST "
            "be the ONLY tool call in that turn; it blocks until the user "
            "replies, so start no other tool before the answer returns. Use a "
